import { Helmet } from 'react-helmet-async'

// Shared per-route/per-item SEO tag set — title, description, canonical,
// Open Graph, and Twitter Card, plus optional JSON-LD structured data.
// Reuses react-helmet-async (installed this round) instead of the old
// imperative setPageMeta()/document.title approach a couple of pages used
// before (CertificatePage.jsx, NewsPostPage.jsx) — Helmet correctly
// restores the previous page's tags on unmount/navigation, which direct
// DOM mutation didn't.
//
// Same disclosed limitation as before: this only changes what a real
// browser (or any crawler that executes JS) sees. index.html's own tags
// are what a non-JS crawler (WhatsApp, LinkedIn) still sees on a route
// that isn't one of the pre-rendered static-meta pages generated by
// scripts/generate-static-meta.js at build time.
export const SITE_NAME = 'MEDWEB-PK'
export const SITE_URL = 'https://medwebpk.com'
export const DEFAULT_DESCRIPTION =
  "MEDWEB-PK is Pakistan's medical education platform — live webinars, expert-designed courses, verified certificates, and a nationwide student ambassador network for healthcare students."
export const DEFAULT_IMAGE = `${SITE_URL}/favicon.png`

export default function SEO({ title, description, path, image, type = 'website', noindex = false, jsonLd, keywords }) {
  const fullTitle = title ? `${title} | ${SITE_NAME}` : `${SITE_NAME} — Pakistan's Medical Education Platform`
  const desc = description || DEFAULT_DESCRIPTION
  const canonical = `${SITE_URL}${path || (typeof window !== 'undefined' ? window.location.pathname : '/')}`
  const img = image || DEFAULT_IMAGE
  const jsonLdList = Array.isArray(jsonLd) ? jsonLd : jsonLd ? [jsonLd] : []
  const keywordsStr = Array.isArray(keywords) ? keywords.join(', ') : keywords

  return (
    <Helmet>
      <title>{fullTitle}</title>
      <meta name="description" content={desc} />
      {keywordsStr && <meta name="keywords" content={keywordsStr} />}
      <link rel="canonical" href={canonical} />
      {noindex && <meta name="robots" content="noindex, nofollow" />}

      <meta property="og:type" content={type} />
      <meta property="og:site_name" content={SITE_NAME} />
      <meta property="og:title" content={fullTitle} />
      <meta property="og:description" content={desc} />
      <meta property="og:image" content={img} />
      <meta property="og:url" content={canonical} />

      <meta name="twitter:card" content="summary_large_image" />
      <meta name="twitter:title" content={fullTitle} />
      <meta name="twitter:description" content={desc} />
      <meta name="twitter:image" content={img} />

      {jsonLdList.map((ld, i) => (
        <script key={i} type="application/ld+json">{JSON.stringify(ld)}</script>
      ))}
    </Helmet>
  )
}
